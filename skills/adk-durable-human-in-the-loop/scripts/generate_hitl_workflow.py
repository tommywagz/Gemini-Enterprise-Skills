REQUIREMENTS_TEMPLATE = "google-adk>=2.0.0\nrequests>=2.31\n"


def render(output_dir, args):
    files = {
        "agent.py": AGENT_PY_TEMPLATE.format(
            app_name=args.app_name, tool_name=args.tool_name,
            agent_name=args.agent_name, agent_var=args.agent_name.replace("-", "_"),
            model=args.model,
        ),
        "hitl_support.py": HITL_SUPPORT_PY_TEMPLATE.format(
            webhook_url=args.webhook_url, secret_env_var=args.secret_env_var,
            app_name=args.app_name,
        ),
        "service.py": SERVICE_PY_TEMPLATE.format(app_name=args.app_name),
        "README.md": README_TEMPLATE.format(
            app_name=args.app_name, agent_name=args.agent_name, tool_name=args.tool_name,
            secret_env_var=args.secret_env_var,
            webhook_url_display=args.webhook_url or "(none configured -- payload printed to stdout)",
        ),
        "requirements.txt": REQUIREMENTS_TEMPLATE,
    }
    return files


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--output-dir", required=True, help="Directory to create/populate (must not already exist)")
    ap.add_argument("--app-name", default="hitl_approval_app")
    ap.add_argument("--agent-name", default="approval_agent")
    ap.add_argument("--tool-name", default="ask_for_approval")
    ap.add_argument("--model", default="gemini-flash-latest")
    ap.add_argument("--webhook-url", default="",
                     help="Where to POST the signed state-holding webhook. Empty = print to stdout instead.")
    ap.add_argument("--secret-env-var", default="HITL_WEBHOOK_SECRET",
                     help="Name of the env var holding the HMAC signing secret (never the secret value itself)")
    ap.add_argument("--dry-run", action="store_true", help="Print the file tree and previews; write nothing")
    args = ap.parse_args()

    for name in (args.app_name, args.agent_name, args.tool_name):
        if not name.isidentifier():
            print(f"error: {name!r} must be a valid Python identifier "
                  "(used as a module-level name in the generated code)", file=sys.stderr)
            sys.exit(2)

    files = render(args.output_dir, args)

    if args.dry_run:
        print(f"Would create {args.output_dir}/ with:")
        for name, content in files.items():
            print(f"  {name}  ({len(content.splitlines())} lines)")
        print("\nDry run only -- no files written. Re-run without --dry-run to generate the project.")
        sys.exit(0)

    if os.path.exists(args.output_dir) and os.listdir(args.output_dir):
        print(f"error: '{args.output_dir}' already exists and is not empty -- refusing to overwrite", file=sys.stderr)
        sys.exit(2)

    os.makedirs(args.output_dir, exist_ok=True)
    for name, content in files.items():
        with open(os.path.join(args.output_dir, name), "w") as f:
            f.write(content)
    print(f"Generated {len(files)} file(s) in {args.output_dir}/")
    print("Next: cd into it, `pip install -r requirements.txt`, set the secret env var, and see README.md")
    sys.exit(0)


if __name__ == "__main__":
    main()
