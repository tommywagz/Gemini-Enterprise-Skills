#!/usr/bin/env python3
"""generate_hitl_workflow.py

Scaffolds a runnable ADK project implementing a durable, asynchronous
Human-in-the-Loop (HITL) approval gate: an `LlmAgent` with a
`LongRunningFunctionTool` that pauses the invocation, records a pending
ticket, and POSTs a signed state-holding webhook to an external dashboard
-- built on the primitives documented in
references/adk_graph_hitl_api.md and the durability rationale in
references/durable_hitl_patterns.md.

This script only writes text files -- it does not import `google-adk` and
has no third-party dependencies, so `--dry-run` (and even a real run) works
with no ADK install. The GENERATED project does depend on `google-adk` and
`requests` to actually run (see the generated requirements.txt).

The generated project's pending-ticket store uses the exact same JSON shape
`scripts/resume_workflow.py`'s `PendingStore` expects, so the resume side of
the gate is NOT regenerated per-project -- point `resume_workflow.py serve`
(or `resume`) at the generated project's `pending_approvals.json` directly.
This keeps signature verification and resume logic in exactly one place.

Usage:
    generate_hitl_workflow.py --output-dir ./my_approval_agent --dry-run
    generate_hitl_workflow.py --output-dir ./my_approval_agent \\
        --app-name expense_approval_app --tool-name ask_for_approval \\
        --agent-name expense_agent --webhook-url https://dashboard.example.com/hitl/incoming \\
        --secret-env-var HITL_WEBHOOK_SECRET

Exit codes: 0 = success (files written, or dry-run preview printed),
2 = usage error (e.g. output dir already exists and is non-empty).
"""
import argparse
import os
import sys

AGENT_PY_TEMPLATE = '''"""{app_name}: durable HITL approval gate agent.

Generated by adk-durable-human-in-the-loop's generate_hitl_workflow.py.
Grounded in ADK's LongRunningFunctionTool + ResumabilityConfig (see this
skill's references/adk_graph_hitl_api.md) -- re-verify against the current
google-adk release before deploying, this surface is still evolving.
"""
from typing import Any

from google.adk.agents import Agent
from google.adk.apps import App, ResumabilityConfig
from google.adk.tools import LongRunningFunctionTool

from hitl_support import record_ticket_and_notify


def {tool_name}(purpose: str, amount: float, tool_context) -> dict[str, Any]:
    """Ask a human approver for approval before proceeding.

    Call this before finalizing any action that needs sign-off (e.g. a
    spend over the configured threshold). Do NOT block here -- this
    function must return quickly with a 'pending' status; the actual
    approval happens out-of-band via the durable webhook + resume flow.

    Args:
        purpose: Short human-readable description of what is being approved.
        amount: The amount (or other primary quantity) requiring approval.
    """
    # ADK assigns the function_call_id for THIS call; tool_context exposes it
    # via the invocation/function-call machinery. record_ticket_and_notify
    # persists everything needed to resume later and sends the signed
    # webhook -- see hitl_support.py.
    ticket = record_ticket_and_notify(
        tool_context=tool_context,
        tool_name="{tool_name}",
        hint=f"Approve {{purpose}} for {{amount}}?",
        payload={{"purpose": purpose, "amount": amount}},
    )
    return {{
        "status": "pending",
        "ticket-id": ticket["ticket_id"],
        "purpose": purpose,
        "amount": amount,
    }}


{agent_var} = Agent(
    name="{agent_name}",
    model="{model}",
    instruction=(
        "You help process requests that require human approval. "
        "Call {tool_name} before finalizing any action needing sign-off, "
        "then tell the user their request is pending approval -- do not "
        "claim it succeeded until a later turn confirms it."
    ),
    tools=[LongRunningFunctionTool(func={tool_name})],
)

# ResumabilityConfig is required for durable resume across process restarts.
# Pair this with a persistent SessionService in service.py (DatabaseSessionService
# or VertexAiSessionService) -- LongRunningFunctionTool has no documented
# restriction against either, unlike Tool Confirmation (see
# references/adk_graph_hitl_api.md \u00a76).
app = App(
    name="{app_name}",
    root_agent={agent_var},
    resumability_config=ResumabilityConfig(is_resumable=True),
)
'''

HITL_SUPPORT_PY_TEMPLATE = '''"""hitl_support.py: ticket recording + signed webhook dispatch for the
durable HITL approval gate. Generated by generate_hitl_workflow.py.

The pending-ticket JSON shape here matches
adk-durable-human-in-the-loop/scripts/resume_workflow.py's PendingStore
exactly, so that script can be pointed directly at PENDING_STORE_PATH below
to handle the resume side -- do not diverge the field names without also
updating the resume script's expectations (see that skill's
references/durable_hitl_patterns.md \u00a72 and \u00a75).
"""
import hashlib
import hmac
import json
import os
import uuid
from datetime import datetime, timezone

import requests

PENDING_STORE_PATH = os.environ.get("HITL_PENDING_STORE", "./pending_approvals.json")
WEBHOOK_URL = "{webhook_url}"
SECRET_ENV_VAR = "{secret_env_var}"


def _now_iso():
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def _canonical_json(obj):
    return json.dumps(obj, sort_keys=True, separators=(",", ":"))


def _sign(body, secret):
    mac = hmac.new(secret.encode("utf-8"), _canonical_json(body).encode("utf-8"), hashlib.sha256)
    return mac.hexdigest()


def _load_store():
    if not os.path.exists(PENDING_STORE_PATH):
        return {{}}
    with open(PENDING_STORE_PATH) as f:
        return json.load(f)


def _save_store(data):
    tmp = PENDING_STORE_PATH + ".tmp"
    with open(tmp, "w") as f:
        json.dump(data, f, indent=2)
    os.replace(tmp, PENDING_STORE_PATH)


def record_ticket_and_notify(tool_context, tool_name, hint, payload, expires_at=None):
    """Persists a pending-approval record and POSTs the signed state-holding
    webhook. Call this from inside a LongRunningFunctionTool BEFORE
    returning its initial 'pending' result -- never block here waiting for
    the human.

    Idempotency note (references/durable_hitl_patterns.md \u00a74): if ADK
    resumes and re-runs this tool call for the same underlying request
    (at-least-once tool execution on workflow resume), calling this twice
    with the same function_call_id will overwrite the same ticket_id
    (derived deterministically below) rather than creating a duplicate.
    """
    function_call_id = getattr(tool_context, "function_call_id", None) or str(uuid.uuid4())
    invocation_id = getattr(getattr(tool_context, "_invocation_context", None), "invocation_id", None) \\
        or os.environ.get("HITL_DEV_INVOCATION_ID", "unknown-invocation")
    session = getattr(tool_context, "session", None)
    session_id = getattr(session, "id", os.environ.get("HITL_DEV_SESSION_ID", "unknown-session"))
    user_id = getattr(session, "user_id", os.environ.get("HITL_DEV_USER_ID", "unknown-user"))

    ticket_id = f"ticket-{{function_call_id}}"  # deterministic -> idempotent re-record on resume

    record = {{
        "app_name": "{app_name}",
        "user_id": user_id,
        "session_id": session_id,
        "invocation_id": invocation_id,
        "function_call_id": function_call_id,
        "tool_name": tool_name,
        "expires_at": expires_at,
        "resolved": False,
    }}
    store = _load_store()
    store[ticket_id] = record
    _save_store(store)

    secret = os.environ.get(SECRET_ENV_VAR)
    if not secret:
        raise RuntimeError(
            f"{{SECRET_ENV_VAR}} is not set -- refusing to send an unsigned HITL webhook. "
            "Set it to a shared secret only this service and the dashboard know."
        )
    webhook_body = {{
        "ticket_id": ticket_id,
        "app_name": record["app_name"],
        "user_id": user_id,
        "session_id": session_id,
        "invocation_id": invocation_id,
        "function_call_id": function_call_id,
        "tool_name": tool_name,
        "hint": hint,
        "payload": payload,
        "requested_at": _now_iso(),
        "expires_at": expires_at,
        "response_url": None,
    }}
    webhook_body["signature"] = _sign(webhook_body, secret)

    if WEBHOOK_URL:
        try:
            requests.post(WEBHOOK_URL, json=webhook_body, timeout=10)
        except requests.RequestException as e:
            # Do not raise -- the ticket is already durably recorded above;
            # a failed notification is retriable (add your own retry/backoff
            # or a dead-letter queue here for production use), losing the
            # webhook is not the same as losing the pending approval.
            print(f"warning: failed to POST HITL webhook for {{ticket_id}}: {{e}}")
    else:
        print(f"warning: WEBHOOK_URL is empty -- printing webhook payload instead of sending it:")
        print(json.dumps(webhook_body, indent=2))

    return {{"ticket_id": ticket_id}}
'''

SERVICE_PY_TEMPLATE = '''"""service.py: run loop wiring session persistence + pause detection for
{app_name}. Generated by generate_hitl_workflow.py.

Demonstrates the event-watching pattern from
references/adk_graph_hitl_api.md \u00a77: `runner.run_async` returns/streams
normally when a LongRunningFunctionTool pauses -- detect the pause via
`event.long_running_tool_ids`, not by waiting for a final response that
will never come this turn.
"""
import asyncio

from google.adk.runners import Runner
from google.adk.sessions import DatabaseSessionService  # swap for VertexAiSessionService in GCP prod
from google.genai import types

from agent import app

# sqlite for local dev; point at a real Postgres/MySQL DSN in production so
# paused invocations survive a process restart (the entire point of this
# gate -- see references/durable_hitl_patterns.md \u00a71).
session_service = DatabaseSessionService(db_url="sqlite:///./{app_name}_sessions.db")
runner = Runner(app=app, session_service=session_service)


async def start_turn(user_id: str, session_id: str, user_text: str):
    await session_service.create_session(app_name="{app_name}", user_id=user_id, session_id=session_id)
    content = types.Content(role="user", parts=[types.Part(text=user_text)])
    async for event in runner.run_async(user_id=user_id, session_id=session_id, new_message=content):
        if event.long_running_tool_ids:
            print(f"[paused] invocation waiting on tool call(s): {{event.long_running_tool_ids}} "
                  "-- a signed webhook has been sent; resume via resume_workflow.py once approved.")
        elif event.content and event.content.parts:
            text = "".join(p.text or "" for p in event.content.parts)
            if text:
                print(f"[{{event.author}}] {{text}}")


if __name__ == "__main__":
    import sys
    user_id = sys.argv[1] if len(sys.argv) > 1 else "demo-user"
    session_id = sys.argv[2] if len(sys.argv) > 2 else "demo-session"
    prompt = sys.argv[3] if len(sys.argv) > 3 else "Please process a $2500 reimbursement for conference travel."
    asyncio.run(start_turn(user_id, session_id, prompt))
'''

